const { chromium, expect } = require('../shop/node_modules/playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1700, height: 1000 } });
    const page = await context.newPage();
    const requests = [], errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await context.addInitScript(() => localStorage.setItem('mkpos.activeModule', 'customers'));
    const customer = { id: 7, name: 'Navigation Customer', phone: '09123', balance: 1500, sale_count: 0 };
    const supplier = { id: 3, name: 'Navigation Supplier', phone: '09234', balance: 1000, purchase_count: 0 };
    let supplierPayment = null;
    let accountNumber = 1;
    const accountSession = () => ({ user: { id: accountNumber, name: `Navigation Owner ${accountNumber}`, role: 'owner' }, business: { id: accountNumber === 1 ? 8 : 9, name: `Navigation Demo ${accountNumber}` }, permissions: ['customers', 'suppliers'], subscription: { is_valid: true, access_type: 'paid' } });
    await page.route('**/api/**', async (route) => {
      const url = new URL(route.request().url());
      if (!url.pathname.startsWith('/api/')) return route.continue();
      const path = url.pathname.slice(4);
      requests.push(path + url.search);
      let body = [];
      if (path === '/auth/me') body = accountSession();
      else if (path === '/auth/login') { accountNumber = 2; body = accountSession(); }
      else if (path === '/app-config') body = { enabled_modules: ['customers', 'suppliers'], language: 'en' };
      else if (path === '/customers') body = { items: [customer], total: 1, account_summary: {} };
      else if (path === '/customers/7/detail') body = { customer, summary: { balance: 1500 }, sales: [], payments: [] };
      else if (path === '/customers/7/sales' || path === '/customers/7/payments') body = { items: [], total: 0 };
      else if (path === '/suppliers') body = { items: [supplier], total: 1, account_summary: {} };
      else if (path === '/suppliers/3') body = { supplier, purchases: [], summary: { balance: supplier.balance }, total: 0, filtered_stats: {} };
      else if (path === '/suppliers/3/payments' && route.request().method() === 'POST') {
        supplierPayment = { ...route.request().postDataJSON(), id: 21, created_at: '2026-10-06 00:00:00' };
        supplier.balance = 750;
        body = supplierPayment;
      }
      else if (path === '/supplier-payments') body = { items: supplierPayment ? [supplierPayment] : [], total: supplierPayment ? 1 : 0 };
      else if (path === '/settings') body = { payment_methods: 'Cash', shop_name: 'Navigation Demo' };
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
    });
    await page.goto('http://127.0.0.1:5174/');
    await expect(page.getByRole('textbox', { name: 'Search customers', exact: true })).toBeVisible();
    const source = await page.locator('.customer-index-table').elementHandle();
    await page.getByRole('textbox', { name: 'Search customers', exact: true }).fill('Navigation');
    await expect.poll(() => requests.some((path) => path.startsWith('/customers?') && path.includes('q=Navigation'))).toBe(true);
    await page.getByRole('button', { name: 'Actions for Navigation Customer', exact: true }).click();
    await page.getByRole('menuitem', { name: 'View customer', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customer sales', exact: true })).toBeVisible();
    await page.getByRole('textbox', { name: 'Search customer sales', exact: true }).fill('Retained history');
    const historyNode = await page.locator('.customer-sale-history-table').elementHandle();
    await page.getByRole('button', { name: 'Payment records', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Customer payment records', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Actions for Navigation Supplier', exact: true })).toBeVisible();
    const count = requests.length;
    await page.goBack();
    await expect(page.getByRole('region', { name: 'Customer payment records', exact: true })).toBeVisible();
    await page.getByRole('button', { name: /Back to Navigation Customer|Back to customer/ }).click();
    await expect(page.getByRole('textbox', { name: 'Search customer sales', exact: true })).toHaveValue('Retained history');
    assert.equal(await page.locator('.customer-sale-history-table').filter({ visible: true }).evaluate((node, original) => node === original, historyNode), true);
    await page.getByRole('button', { name: 'Back to Customers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customers', exact: true })).toHaveValue('Navigation');
    assert.equal(await page.locator('.customer-index-table').filter({ visible: true }).evaluate((node, original) => node === original, source), true);
    assert.equal(requests.length, count);
    await page.goForward();
    await expect(page.getByRole('textbox', { name: 'Search customer sales', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Customers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customer sales', exact: true })).toHaveValue('Retained history');
    await page.getByRole('button', { name: 'Back to Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toBeVisible();
    assert.equal(requests.length, count);
    assert.deepEqual(errors, []);
    const supplierSource = await page.locator('.supplier-table').filter({ visible: true }).elementHandle();
    await page.getByRole('textbox', { name: 'Search suppliers', exact: true }).fill('Navigation');
    await expect.poll(() => requests.some(path => path.startsWith('/suppliers?') && path.includes('q=Navigation'))).toBe(true);
    await page.getByRole('button', { name: 'Actions for Navigation Supplier', exact: true }).click();
    await page.getByRole('menuitem', { name: 'View supplier', exact: true }).click();
    const historySearch = page.getByRole('textbox', { name: 'Search supplier purchases', exact: true });
    await expect(historySearch).toBeVisible();
    await historySearch.fill('Retained supplier history');
    const supplierHistory = await page.locator('.purchase-history-table').filter({ visible: true }).elementHandle();
    await page.getByRole('button', { name: 'Payment records', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Supplier payment records', exact: true })).toBeVisible();
    const supplierPayments = await page.locator('.supplier-payment-records-table').filter({ visible: true }).elementHandle();
    await page.getByRole('button', { name: 'Customers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customer sales', exact: true })).toBeVisible();
    const supplierCount = requests.length;
    await page.goBack();
    await expect(page.getByRole('region', { name: 'Supplier payment records', exact: true })).toBeVisible();
    assert.equal(await page.locator('.supplier-payment-records-table').filter({ visible: true }).evaluate((node, original) => node === original, supplierPayments), true);
    await page.getByRole('button', { name: /Back to Navigation Supplier|Back to supplier/ }).click();
    await expect(historySearch).toBeVisible();
    await expect(historySearch).toHaveValue('Retained supplier history');
    assert.equal(await page.locator('.purchase-history-table').filter({ visible: true }).evaluate((node, original) => node === original, supplierHistory), true);
    await page.getByRole('button', { name: 'Back to Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('Navigation');
    assert.equal(await page.locator('.supplier-table').filter({ visible: true }).evaluate((node, original) => node === original, supplierSource), true);
    await page.goForward();
    await expect(historySearch).toHaveValue('Retained supplier history');
    assert.equal(requests.length, supplierCount);
    await page.getByRole('button', { name: 'Back to Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('Navigation');
    await page.getByRole('button', { name: 'Actions for Navigation Supplier', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Payments', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Supplier payment records', exact: true })).toBeVisible();
    const directCount = requests.length;
    await page.getByRole('button', { name: 'Back to Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('Navigation');
    assert.equal(await page.locator('.supplier-table').filter({ visible: true }).evaluate((node, original) => node === original, supplierSource), true);
    await page.goForward();
    await expect(page.getByRole('region', { name: 'Supplier payment records', exact: true })).toBeVisible();
    assert.equal(requests.length, directCount);
    await page.getByRole('button', { name: 'Record payment', exact: true }).click();
    const paymentForm = page.getByRole('dialog', { name: 'Record Supplier Payment', exact: true });
    await paymentForm.getByLabel('Amount', { exact: true }).fill('250');
    await paymentForm.getByLabel('Note', { exact: true }).fill('Browser reconciliation payment');
    await paymentForm.getByRole('button', { name: 'Record payment', exact: true }).click();
    await expect(page.getByText('Browser reconciliation payment', { exact: true })).toBeVisible();
    await expect.poll(() => requests.filter(path => path.startsWith('/suppliers?')).length).toBeGreaterThan(2);
    const mutationCount = requests.length;
    await page.getByRole('button', { name: 'Back to Suppliers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('Navigation');
    await expect(page.locator('.supplier-table').filter({ visible: true }).getByText('750 Ks', { exact: true })).toBeVisible();
    assert.equal(await page.locator('.supplier-table').filter({ visible: true }).evaluate((node, original) => node === original, supplierSource), true);
    await page.goForward();
    await expect(page.getByText('Browser reconciliation payment', { exact: true })).toBeVisible();
    assert.equal(requests.length, mutationCount);
    await page.getByRole('button', { name: 'Record payment', exact: true }).click();
    const abandonedForm = page.getByRole('dialog', { name: 'Record Supplier Payment', exact: true });
    const privateNote = abandonedForm.getByRole('textbox', { name: /^Note/ });
    await privateNote.fill('Private first-account draft');
    const abandonedNote = await privateNote.elementHandle();
    await abandonedForm.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible();
    assert.equal(await source.evaluate(node => node.isConnected), false);
    assert.equal(await supplierSource.evaluate(node => node.isConnected), false);
    assert.equal(await abandonedNote.evaluate(node => node.isConnected), false);
    const loginEmail = page.getByRole('textbox', { name: 'Email address', exact: true });
    await loginEmail.fill('Unsubmitted@example.test');
    const loginNode = await loginEmail.elementHandle();
    const loginPassword = page.getByLabel('Password', { exact: true });
    await loginPassword.fill('Private login draft');
    await page.getByRole('link', { name: 'Create business account', exact: true }).click();
    const signupBusiness = page.getByRole('textbox', { name: 'Business name', exact: true });
    await signupBusiness.fill('Unsubmitted business');
    const businessNode = await signupBusiness.elementHandle();
    const authCount = requests.length;
    await page.goBack();
    await expect(loginEmail).toHaveValue('Unsubmitted@example.test');
    await expect(page.getByLabel('Password', { exact: true }).filter({ visible: true })).toHaveValue('Private login draft');
    assert.equal(await loginEmail.evaluate((node, original) => node === original, loginNode), true);
    await page.goForward();
    await expect(signupBusiness).toHaveValue('Unsubmitted business');
    assert.equal(await signupBusiness.evaluate((node, original) => node === original, businessNode), true);
    await page.getByRole('link', { name: 'Sign in instead', exact: true }).click();
    await expect(loginEmail).toHaveValue('Unsubmitted@example.test');
    assert.equal(requests.length, authCount);
    await loginEmail.fill('next-owner@example.test');
    await page.getByLabel('Password', { exact: true }).filter({ visible: true }).fill('Next account password');
    await page.getByRole('button', { name: 'Sign in to MKPOS', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('');
    assert.equal(await loginNode.evaluate(node => node.isConnected), false);
    assert.equal(await businessNode.evaluate(node => node.isConnected), false);
    assert.equal(await supplierSource.evaluate(node => node.isConnected), false);
    const freshTable = await page.locator('.supplier-table').filter({ visible: true }).elementHandle();
    await page.getByRole('button', { name: 'Customers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customers', exact: true })).toHaveValue('');
    const freshCount = requests.length;
    await page.goBack();
    await expect(page.getByRole('textbox', { name: 'Search suppliers', exact: true })).toHaveValue('');
    assert.equal(await page.locator('.supplier-table').filter({ visible: true }).evaluate((node, original) => node === original, freshTable), true);
    assert.equal(requests.length, freshCount);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ moduleBack: true, nestedBack: true, supplierNestedBackAndForward: true, supplierDirectPaymentBackForward: true, paymentMutationRetainsSource: true, sameSourceNodes: true, logoutClearsAccountCache: true, nextBusinessStartsFresh: true, nextAccountBackRetainsOwnSource: true, pageErrors: errors.length }));
    await context.close();
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
