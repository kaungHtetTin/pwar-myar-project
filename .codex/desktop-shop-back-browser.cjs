const { chromium, expect } = require('../shop/node_modules/playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1700, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem('mkpos.activeModule', 'shop'));
    const page = await context.newPage(), requests = [], errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const customer = { id: 'account:42', customer_key: 'account:42', customer_name: 'Navigation Buyer', phone: '091234', account_type: 'account', purchase_count: 2, last_purchase_at: '2026-10-02 08:00:00' };
    const order = { id: 12, reference: 'O-NAVIGATION', created_at: '2026-10-03 08:00:00', total: 1500, currency: 'Ks', status: 'accepted', payment_status: 'unpaid', fulfillment: 'pickup', customer_key: customer.customer_key, customer_name: customer.customer_name };
    const thread = { uuid: 'demo-thread', customer_key: customer.customer_key, customer_name: customer.customer_name, owner_read_id: 0, customer_read_id: 0 };
    let deferOrders = false, releaseOrders;
    await context.route('**/api/**', async route => {
      const url = new URL(route.request().url());
      if (!url.pathname.startsWith('/api/')) return route.continue();
      const path = url.pathname.slice(4); requests.push(path + url.search);
      let body = { items: [], total: 0 };
      if (path === '/auth/me') body = { user: { id: 1, role: 'owner', name: 'Navigation Owner' }, business: { id: 8, name: 'Navigation Demo', timezone: 'Asia/Rangoon' }, subscription: { is_valid: true, access_type: 'paid' } };
      else if (path === '/app-config') body = { enabled_modules: ['shop', 'customers'], language: 'en' };
      else if (path === '/shop-admin/owner-location') body = { submitted: true };
      else if (path === '/shop-admin/report') body = { states: [] };
      else if (path === '/shop-admin/orders') {
        if (deferOrders) await new Promise(resolve => { releaseOrders = resolve; });
        body = { items: [order], total: 1 };
      }
      else if (path === '/shop-admin/orders/12/transition' && route.request().method() === 'POST') {
        order.status = route.request().postDataJSON().status;
        body = order;
      }
      else if (path === '/shop-admin/orders/12') body = { ...order, payment_method: { name: 'Cash', provider: 'manual' }, payments: [], items: [], events: [], delivery_fee: 0 };
      else if (path === '/shop-admin/customers') body = { items: [customer], total: 1 };
      else if (path.includes('/customers/') && path.endsWith('/history')) body = { items: [order], total: 1 };
      else if (path.startsWith('/shop-admin/customers/')) body = { customer, report: { total_orders: 2, completed_orders: 1, active_orders: 1, currencies: [{ currency: 'Ks', completed_spend: 1500, average_purchase: 1500 }] } };
      else if (path === '/shop-admin/chat/config') body = { enabled: true, realtime_enabled: false, channel: 'private-shop.chat.business.8' };
      else if (path === '/shop-admin/chat') body = { items: [thread], total: 1, next_cursor: null };
      else if (path.includes('/demo-thread/messages')) body = { items: [], thread, has_more: false };
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
    });
    await page.goto('http://127.0.0.1:5174/');
    const sections = page.getByRole('navigation', { name: 'Shop management sections' });
    await sections.getByRole('button', { name: 'Customers', exact: true }).click();
    const sourceSearch = page.getByRole('textbox', { name: 'Search shop customers', exact: true });
    await sourceSearch.fill('Navigation');
    await expect.poll(() => requests.some(path => path.startsWith('/shop-admin/customers?') && path.includes('q=Navigation'))).toBe(true);
    const source = await page.getByRole('button', { name: 'Navigation Buyer', exact: true }).elementHandle();
    await page.getByRole('button', { name: 'Navigation Buyer', exact: true }).click();
    const historySearch = page.getByRole('textbox', { name: 'Search customer order history', exact: true });
    await historySearch.fill('O-NAVIGATION');
    await expect.poll(() => requests.some(path => path.includes('/history?') && path.includes('O-NAVIGATION'))).toBe(true);
    const history = await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).elementHandle();
    await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Order history', exact: true })).toBeVisible();
    const count = requests.length;
    await page.getByRole('button', { name: 'Back to customer', exact: true }).click();
    await expect(historySearch).toBeVisible();
    await expect(historySearch).toHaveValue('O-NAVIGATION');
    assert.equal(await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).evaluate((node, original) => node === original, history), true);
    await page.getByRole('button', { name: 'Back to customers', exact: true }).click();
    await expect(sourceSearch).toHaveValue('Navigation');
    assert.equal(await page.getByRole('button', { name: 'Navigation Buyer', exact: true }).evaluate((node, original) => node === original, source), true);
    assert.equal(requests.length, count);
    await sections.getByRole('button', { name: 'Chat', exact: true }).click();
    await page.getByRole('button', { name: 'Navigation Buyer', exact: true }).click();
    const draft = page.getByRole('textbox', { name: 'Message', exact: true });
    await draft.fill('Unsent reply preserved');
    const draftNode = await draft.elementHandle();
    await page.getByRole('button', { name: 'View customer Navigation Buyer', exact: true }).click();
    await expect(historySearch).toBeVisible();
    await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Order history', exact: true })).toBeVisible();
    const chatCount = requests.length;
    await page.goBack();
    await expect(historySearch).toBeVisible();
    await page.getByRole('button', { name: 'Back to chat', exact: true }).click();
    await expect(draft).toHaveValue('Unsent reply preserved');
    assert.equal(await draft.evaluate((node, original) => node === original, draftNode), true);
    assert.equal(requests.length, chatCount);
    await page.goForward();
    await expect(historySearch).toBeVisible();
    assert.equal(requests.length, chatCount);
    await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Customers', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Search customers', exact: true })).toBeVisible();
    const moduleCount = requests.length;
    await page.goBack();
    await expect(historySearch).toBeVisible();
    await page.getByRole('button', { name: 'Back to chat', exact: true }).click();
    await expect(draft).toHaveValue('Unsent reply preserved');
    assert.equal(await draft.evaluate((node, original) => node === original, draftNode), true);
    assert.equal(requests.length, moduleCount);
    await sections.getByRole('button', { name: 'Orders', exact: true }).click();
    const orderSearch = page.getByRole('textbox', { name: 'Search online orders', exact: true });
    await orderSearch.fill('O-NAVIGATION');
    await expect.poll(() => requests.some(path => path.startsWith('/shop-admin/orders?') && path.includes('q=O-NAVIGATION'))).toBe(true);
    const orderSource = await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).elementHandle();
    await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Order history', exact: true })).toBeVisible();
    const ordersCount = requests.length;
    await page.getByRole('button', { name: 'Back to orders', exact: true }).click();
    await expect(orderSearch).toHaveValue('O-NAVIGATION');
    assert.equal(await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).evaluate((node, original) => node === original, orderSource), true);
    assert.equal(requests.length, ordersCount);
    await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
    const cancelDialog = page.getByRole('dialog', { name: 'Cancel order', exact: true });
    const reason = cancelDialog.getByRole('textbox', { name: /^Reason \(required for cancellation or failed delivery\)/ });
    await reason.fill('Unsubmitted retained cancellation');
    const reasonNode = await reason.elementHandle();
    const closeCount = requests.length;
    await page.goBack();
    await expect(orderSearch).toBeVisible();
    await orderSearch.press('Escape');
    await page.goForward();
    await expect(cancelDialog).toBeVisible();
    await expect(reason).toHaveValue('Unsubmitted retained cancellation');
    assert.equal(await reason.evaluate((node, original) => node === original, reasonNode), true);
    await cancelDialog.getByRole('button', { name: 'Close', exact: true }).click();
    await expect(cancelDialog).not.toBeVisible();
    assert.equal(requests.length, closeCount);
    await page.getByRole('button', { name: 'Start packing', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Ready for pickup', exact: true })).toBeVisible();
    deferOrders = true;
    await page.getByRole('button', { name: 'Back to orders', exact: true }).click();
    await expect.poll(() => Boolean(releaseOrders)).toBe(true);
    await expect(orderSearch).toHaveValue('O-NAVIGATION');
    assert.equal(await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).evaluate((node, original) => node === original, orderSource), true);
    await expect(page.getByRole('table', { name: 'Online orders', exact: true }).getByText('accepted', { exact: true })).toBeVisible();
    deferOrders = false;
    releaseOrders();
    await expect(page.getByRole('table', { name: 'Online orders', exact: true }).getByText('packing', { exact: true })).toBeVisible();
    const afterMutation = requests.length;
    await page.goForward();
    await expect(page.getByRole('button', { name: 'Ready for pickup', exact: true })).toBeVisible();
    await page.goBack();
    await expect(orderSearch).toHaveValue('O-NAVIGATION');
    assert.equal(requests.length, afterMutation);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ customersOrderNestedBack: true, chatCustomerOrderBack: true, chatDraftSameNode: true, forwardPreservesCustomer: true, crossModuleBack: true, filteredOrdersBack: true, hiddenModalEscapePreservesDraft: true, mutationKeepsSourceRowWhilePending: true, mutationBackForwardNoRequests: true, pageErrors: 0 }));
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
