const { chromium, expect } = require('../shop/node_modules/playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1700, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem('mkpos.activeModule', 'customers'));
    const page = await context.newPage(), calls = [], errors = [];
    page.on('pageerror', e => errors.push(e.message));
    let unread = 8;
    const customer = { id: 7, name: 'Navigation Buyer', phone: '09123', balance: 1000, sale_count: 0 };
    const order = { id: 12, reference: 'O-NAVIGATION', created_at: '2026-10-03 08:00:00', total: 1500, currency: 'Ks', status: 'accepted', payment_status: 'unpaid', fulfillment: 'pickup', customer_name: customer.name };
    await context.route('**/api/**', async route => {
      const path = new URL(route.request().url()).pathname.slice(4); calls.push(path);
      let body = { items: [], total: 0 };
      if (path === '/auth/me') body = { user: { id: 1, role: 'owner', name: 'Navigation Owner' }, business: { id: 8, name: 'Navigation Shop' }, subscription: { is_valid: true, access_type: 'paid' } };
      else if (path === '/app-config') body = { enabled_modules: ['customers', 'shop'], language: 'en' };
      else if (path === '/customers') body = { items: [customer], total: 1, account_summary: {} };
      else if (path === '/shop-admin/owner-location') body = { submitted: true };
      else if (path === '/shop-admin/report') body = { states: [] };
      else if (path === '/shop-admin/orders') body = { items: [order], total: 1 };
      else if (path === '/shop-admin/orders/12') body = { ...order, items: [], events: [], payment_method: { name: 'Cash', provider: 'manual' }, payments: [], delivery_fee: 0 };
      else if (path === '/shop-admin/chat/config') body = { enabled: true, realtime_enabled: false, channel: 'private-shop.chat.business.8' };
      else if (path === '/shop-admin/chat/unread') body = { unread_count: unread };
      else if (path === '/shop-admin/chat') body = { items: [], total: 0, next_cursor: null };
      await route.fulfill({ contentType: 'application/json', body: JSON.stringify(body) });
    });
    await page.goto('http://127.0.0.1:5174/');
    const search = page.getByRole('textbox', { name: 'Search customers', exact: true });
    await expect(page.getByRole('button', { name: 'Actions for Navigation Buyer' })).toBeVisible();
    await search.fill('Navigation');
    await expect.poll(() => calls.filter(c => c === '/customers').length).toBeGreaterThan(1);
    const source = await page.locator('.customer-index-table').elementHandle();
    await page.getByRole('button', { name: 'Chat, 8 unread messages' }).click();
    await expect(page.getByRole('heading', { name: 'Your customer conversations' })).toBeVisible();
    const chat = page.locator('.workspace-chat-button');
    assert.equal(await chat.evaluate(node => getComputedStyle(node).overflow), 'visible');
    await page.screenshot({ path: '.codex/global-chat.png' });
    const count = calls.filter(c => c === '/customers').length;
    await page.getByRole('button', { name: 'Back to Customers', exact: true }).click();
    await expect(search).toHaveValue('Navigation');
    assert.equal(await page.locator('.customer-index-table').evaluate((node, old) => node === old, source), true);
    assert.equal(calls.filter(c => c === '/customers').length, count);
    await page.goForward();
    await expect(page.getByRole('heading', { name: 'Your customer conversations' })).toBeVisible();
    await page.goBack();
    await expect(search).toHaveValue('Navigation');
    await chat.focus();
    await page.keyboard.press('Enter');
    await expect(page.getByRole('heading', { name: 'Your customer conversations' })).toBeVisible();
    const historyLength = await page.evaluate(() => history.length);
    await chat.click();
    assert.equal(await page.evaluate(() => history.length), historyLength);
    const sections = page.getByRole('navigation', { name: 'Shop management sections' });
    await sections.getByRole('button', { name: 'Orders', exact: true }).click();
    await page.getByRole('button', { name: 'O-NAVIGATION', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Order history', exact: true })).toBeVisible();
    await chat.click();
    await expect(page.getByRole('heading', { name: 'Your customer conversations' })).toBeVisible();
    await page.getByRole('button', { name: 'Back to previous screen' }).click();
    await expect(page.getByRole('button', { name: 'Order history', exact: true })).toBeVisible();
    assert.equal(new URL(page.url()).searchParams.get('shopOrder'), '12');
    unread = 0;
    await page.evaluate(() => window.dispatchEvent(new Event('mkpos:shop-chat-read')));
    await expect(chat).toHaveAccessibleName('Chat');
    await expect(chat.locator('.workspace-chat-badge')).toHaveCount(0);
    assert.deepEqual(errors, []);
    console.log('PASS: global chat from customers and order detail, mouse/keyboard, badge updates, app-bar/browser Back, preserved source draft/DOM without list refetch, no duplicate history entry.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
