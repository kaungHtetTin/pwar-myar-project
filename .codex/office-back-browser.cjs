const { chromium, expect } = require('../shop/node_modules/playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
    const requests = [], errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const business = { id: 9, name: 'Navigation Business', owner_name: 'Demo Owner', currency: 'Ks', prospect: 'setup', sales_30d: 2, product_count: 8 };
    const unavailableBusiness = { ...business, id: 10, name: 'Unavailable Business' };
    let savedTutorial = null, holdTutorialRefresh = false, releaseTutorialRefresh;
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url());
      if (!url.pathname.startsWith('/api/')) return route.continue();
      const path = url.pathname.slice(4);
      requests.push(path + url.search);
      let body = { items: [] };
      if (path === '/office/auth/me') body = { admin: { id: 1, name: 'Office Demo', email: 'office@example.test' } };
      else if (path === '/office/auth/login') body = { admin: { id: 2, name: 'Other Office Demo', email: 'other@example.test' } };
      else if (path === '/office/businesses') body = { items: [business, unavailableBusiness], total: 50, page: Number(url.searchParams.get('page') || 1), last_page: 2, per_page: 25, summary: { total: 50, access_counts: {} } };
      else if (path === '/office/businesses/10') return route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ message: 'Demo business unavailable' }) });
      else if (path === '/office/businesses/9') body = { business, billing: { subscription: null, is_valid: false, reason: 'none' }, billing_history: [] };
      else if (path === '/office/tutorials' && route.request().method() === 'POST') {
        savedTutorial = { id: 2, title: 'Saved navigation tutorial', description: 'Saved demo description', youtube_url: 'https://youtu.be/abcdefghijk', is_published: false, sort_order: 0 };
        body = savedTutorial;
      }
      else if (path === '/office/tutorials') {
        if (holdTutorialRefresh) await new Promise(resolve => { releaseTutorialRefresh = resolve; });
        body = { items: [{ id: 1, title: 'Navigation tutorial', description: 'Demo', youtube_url: 'https://youtu.be/abcdefghijk', is_published: true, sort_order: 1 }, ...(savedTutorial ? [savedTutorial] : [])], total: savedTutorial ? 2 : 1, page: 1, last_page: 1 };
      }
      else if (path === '/office/financial-report') body = null;
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
    });
    await page.goto('http://127.0.0.1:5175/');
    await page.getByRole('button', { name: 'Businesses', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Search businesses' }).fill('Navigation');
    await expect.poll(() => requests.some(path => path.includes('q=Navigation'))).toBe(true);
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    await expect(page.getByText('Page 2 of 2', { exact: true })).toBeVisible();
    await page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true }).check();
    const source = await page.locator('.office-business-table').elementHandle();
    await page.getByRole('button', { name: 'Actions for Navigation Business', exact: true }).click();
    await page.getByRole('menuitem', { name: 'View business', exact: true }).click();
    const draft = page.getByPlaceholder('At least 8 characters');
    await draft.fill('Unsubmitted demo draft');
    const draftNode = await draft.elementHandle();
    const count = requests.length;
    await page.getByRole('button', { name: 'Back to Businesses', exact: true }).click();
    await expect(page.getByRole('searchbox', { name: 'Search businesses' })).toHaveValue('Navigation');
    await expect(page.getByText('Page 2 of 2', { exact: true })).toBeVisible();
    await expect(page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true })).toBeChecked();
    assert.equal(await page.locator('.office-business-table').evaluate((node, original) => node === original, source), true);
    await page.goForward();
    await expect(draft).toHaveValue('Unsubmitted demo draft');
    assert.equal(await draft.evaluate((node, original) => node === original, draftNode), true);
    await page.goBack();
    await expect(page.getByRole('searchbox', { name: 'Search businesses' })).toBeVisible();
    assert.equal(requests.length, count);
    await page.getByRole('button', { name: 'Tutorials', exact: true }).click();
    await expect(page.getByText('Navigation tutorial', { exact: true })).toBeVisible();
    const tutorialSource = await page.locator('[data-retained-view]:not([hidden]) table').filter({ visible: true }).elementHandle();
    await page.getByRole('button', { name: 'Add tutorial', exact: true }).click();
    await page.getByLabel('Title', { exact: true }).fill('Unsent tutorial draft');
    const tutorialDraft = await page.getByLabel('Title', { exact: true }).elementHandle();
    await page.getByRole('button', { name: 'Businesses', exact: true }).click();
    await expect(page.getByRole('searchbox', { name: 'Search businesses' })).toBeVisible();
    const nestedCount = requests.length;
    await page.goBack();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Unsent tutorial draft');
    assert.equal(await page.getByLabel('Title', { exact: true }).evaluate((node, original) => node === original, tutorialDraft), true);
    await page.getByRole('button', { name: 'Back to tutorials', exact: true }).click();
    await expect(page.getByText('Navigation tutorial', { exact: true })).toBeVisible();
    assert.equal(await page.locator('table').filter({ visible: true }).evaluate((node, original) => node === original, tutorialSource), true);
    await page.goForward();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Unsent tutorial draft');
    assert.equal(requests.length, nestedCount);
    await page.getByLabel('Title', { exact: true }).fill('Saved navigation tutorial');
    await page.getByLabel('YouTube link', { exact: false }).fill('https://youtu.be/abcdefghijk');
    await page.getByLabel('Description', { exact: false }).fill('Saved demo description');
    holdTutorialRefresh = true;
    await page.getByRole('button', { name: 'Save tutorial', exact: true }).click();
    await expect.poll(() => typeof releaseTutorialRefresh).toBe('function');
    await expect(page.locator('.office-tutorial-table').filter({ visible: true })).toBeVisible();
    assert.equal(await page.locator('.office-tutorial-table').filter({ visible: true }).evaluate((node, original) => node === original, tutorialSource), true);
    holdTutorialRefresh = false; releaseTutorialRefresh();
    await expect(page.getByText('Saved navigation tutorial', { exact: true })).toBeVisible();
    assert.equal(await page.locator('.office-tutorial-table').filter({ visible: true }).evaluate((node, original) => node === original, tutorialSource), true);
    const savedCount = requests.length;
    await page.goForward();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Saved navigation tutorial');
    await page.getByRole('button', { name: 'Back to tutorials', exact: true }).click();
    await expect(page.getByText('Saved navigation tutorial', { exact: true })).toBeVisible();
    assert.equal(requests.length, savedCount);
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Sign in to Office', exact: true })).toBeVisible();
    assert.equal(await source.evaluate(node => node.isConnected), false);
    assert.equal(await tutorialDraft.evaluate(node => node.isConnected), false);
    await page.getByLabel('Email address', { exact: true }).fill('other@example.test');
    await page.getByPlaceholder('Enter your password', { exact: true }).fill('Demo other password');
    await page.getByRole('button', { name: 'Sign in to Office', exact: true }).click();
    await page.getByRole('button', { name: 'Businesses', exact: true }).click();
    await expect(page.getByRole('searchbox', { name: 'Search businesses', exact: true })).toHaveValue('');
    await expect(page.getByText('Page 1 of 2', { exact: true })).toBeVisible();
    await expect(page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true })).not.toBeChecked();
    const errorSource = await page.locator('.office-business-table').elementHandle();
    await page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true }).check();
    await page.getByRole('button', { name: 'Actions for Unavailable Business', exact: true }).click();
    await page.getByRole('menuitem', { name: 'View business', exact: true }).click();
    await expect(page.getByText('Demo business unavailable', { exact: true })).toBeVisible();
    const errorCount = requests.length;
    await page.getByRole('button', { name: 'Back to businesses', exact: true }).click();
    await expect(page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true })).toBeChecked();
    assert.equal(await page.locator('.office-business-table').evaluate((node, original) => node === original, errorSource), true);
    assert.equal(requests.length, errorCount);
    await page.goForward();
    await expect(page.getByText('Demo business unavailable', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Back to Businesses', exact: true }).click();
    await expect(page.getByRole('checkbox', { name: 'Select Navigation Business', exact: true })).toBeChecked();
    assert.equal(requests.length, errorCount);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ appBarBack: true, browserBackForward: true, sourceSelectionAndPage: true, sameSourceNodes: true, tutorialModuleBack: true, tutorialDraftForward: true, saveRetainsTableWhileReconciling: true, savedBackForwardNoRequests: true, logoutClearsCache: true, nextAccountFresh: true, pageErrors: 0 }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
