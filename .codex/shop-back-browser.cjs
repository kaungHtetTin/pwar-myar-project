    const page = await context.newPage();
    const requests = [], errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    const product = { id: 7, name: 'Navigation Tea', store_slug: 'demo', store_name: 'Navigation Shop', category: 'Tea', available_quantity: 100, price: 1000, currency: 'Ks', unit_name: 'Pack' };
