import React from 'react';
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { ChatAlerts } from './ChatAlerts';

afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); });
it('suppresses alerts on the chat page without stopping presence or replaying messages on return', async () => {
  vi.useFakeTimers();
  let feed = { enabled: true, cursor: 10, unread_count: 1, items: [] };
  const api = vi.fn(async path => path.includes('/notifications') ? feed : {});
  const view = render(<><div className="shop-chat-workspace" /><ChatAlerts apiRequest={api} basePath="/chat" /></>);
  await act(async () => {});
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  expect(api).toHaveBeenCalledWith('/chat/presence', { method: 'POST', body: '{}' });
  feed = { ...feed, cursor: 11, items: [{ id: 11, name: 'Buyer', preview: 'During chat' }] };
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  view.rerender(<><div className="shop-chat-workspace" hidden /><ChatAlerts apiRequest={api} basePath="/chat" /></>);
  await act(async () => {});
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  feed = { ...feed, cursor: 12, items: [{ id: 12, name: 'Buyer', preview: 'After leaving chat' }] };
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.getByRole('status')).toHaveTextContent('After leaving chat');
  view.rerender(<><div className="shop-chat-workspace" /><ChatAlerts apiRequest={api} basePath="/chat" /></>);
  await act(async () => {});
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
});
it('shows incoming messages outside chat, dismisses once, and alerts for a newer message', async () => {
  vi.useFakeTimers();
  let feed = { enabled: true, cursor: 10, unread_count: 0, items: [] };
  const api = vi.fn(async path => path.includes('/notifications') ? feed : { ok: true });
  const open = vi.fn();
  render(<ChatAlerts apiRequest={api} basePath="/chat" onOpen={open} />);
  await act(async () => {});
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  expect(api).toHaveBeenCalledWith('/chat/presence', { method: 'POST', body: '{}' });
  feed = { enabled: true, cursor: 11, unread_count: 1, items: [{ id: 11, name: 'Buyer', preview: 'Hello', uuid: 'thread' }] };
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.getByRole('status')).toHaveTextContent('New message from Buyer');
  expect(api).toHaveBeenCalledWith('/chat/notifications?after_id=10');
  fireEvent.click(screen.getByRole('button', { name: 'Dismiss chat notification' }));
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  feed = { ...feed, cursor: 12, items: [{ id: 12, name: 'Buyer', preview: 'A second message', uuid: 'thread' }] };
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  fireEvent.click(screen.getByRole('button', { name: 'Open chat' }));
  expect(open).toHaveBeenCalledWith(expect.objectContaining({ id: 12, uuid: 'thread' }));
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
});
it('keeps existing unread messages in the badge without replaying an alert on login', async () => {
  vi.useFakeTimers();
  let unread = 3;
  const api = vi.fn(async path => path.includes('/notifications') ? { enabled: true, cursor: 7, unread_count: unread, items: [] } : {});
  render(<ChatAlerts apiRequest={api} basePath="/chat" />);
  await act(async () => {});
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
  unread = 0;
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(screen.queryByRole('status')).not.toBeInTheDocument();
});
