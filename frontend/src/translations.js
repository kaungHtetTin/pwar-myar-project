let currentLanguage = 'en';

export function setCurrentLanguage(language) {
  currentLanguage = language === 'my' ? 'my' : 'en';
  document.documentElement.lang = currentLanguage;
}

export function getCurrentLanguage() {
  return currentLanguage;
}

export function translateText(value, language = currentLanguage) {
  const source = String(value ?? '');
  if (language !== 'my' || !source.trim()) return source;
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const clean = source.trim();
  if (clean.includes('\n')) {
    const translatedLines = clean.split('\n').map((line) => translateText(line, language).trimEnd());
    return `${leading}${translatedLines.join('\n')}${trailing}`;
  }
  if (UI_TEXT[clean]) return `${leading}${UI_TEXT[clean]}${trailing}`;
  for (const [pattern, replacement] of MESSAGE_PATTERNS) {
    if (pattern.test(clean)) return `${leading}${clean.replace(pattern, replacement)}${trailing}`;
  }
  return source;
}

function valueAtPath(dictionary, path) {
  return path.split('.').reduce((value, key) => value?.[key], dictionary);
}

export function getTranslator(language = 'en') {
  return function translate(path) {
    const english = valueAtPath(translations.en, path) || path;
    return language === 'my' ? translateText(english, 'my') : english;
  };
}
