export function sellText(key, language, variables = {}, fallback = '') {
  const template = language === 'my' ? MYANMAR_TEXT[key] : fallback;
  return String(template || fallback).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ''));
}

export function sellOptionLabel(value, language) {
  return language === 'my' ? OPTION_LABELS[value] || value : value;
}
