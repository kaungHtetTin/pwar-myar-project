export function featureText(value, language = 'en') {
  const source = String(value ?? '');
  if (language !== 'my') return source;
  const clean = source.trim();
  if (NEW_FEATURE_MESSAGES[clean]) return source.replace(clean, () => NEW_FEATURE_MESSAGES[clean]);
  for (const [pattern, replacement] of NEW_FEATURE_PATTERNS) {
    if (pattern.test(clean)) return source.replace(clean, () => clean.replace(pattern, replacement));
  }
  return source;
}

export function quotaRemainingText(remaining, limit, percent, language = 'en') {
  return language === 'my'
    ? `ယခုတစ်ပတ် AI မေးမြန်းခွင့် ${limit} ခုအနက် ${remaining} ခု ကျန်သည် (${percent}%)`
    : `${remaining} of ${limit} AI requests remaining this week (${percent}%)`;
}
