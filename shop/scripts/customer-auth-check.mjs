import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 393, height: 852 } });
page.setDefaultTimeout(10000);
const calls = [];
let loginAttempts = 0;
try {
  await page.route('**/ecommerce/**', async route => {
    const path = new URL(route.request().url()).pathname.split('/ecommerce')[1];
    calls.push(path);
    if (path === '/customer/login' && ++loginAttempts === 1) return route.fulfill({ status: 422, json: { message: 'Incorrect email or password.' } });
    if (['/customer/login', '/customer/register'].includes(path)) return route.fulfill({ json: { access_token: 'mock-only', customer: { id: 77, name: 'Test Buyer', email: 'buyer@example.test' } } });
    await route.fulfill({ json: path === '/chat/notifications' ? { enabled: false, unread_count: 0, items: [] } : { items: [], has_more: false } });
  });
  await page.goto('http://127.0.0.1:5177/#/marketplace');
  const search = page.getByPlaceholder('Search products or categories');
  await search.fill('Retained product search');
  const initialLoads = () => calls.filter(path => path === '/marketplace/products').length;
  const loads = initialLoads();
  await page.locator('.mobile-navigation').getByRole('link', { name: 'Me', exact: true }).click();
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor();
  assert.equal(await page.locator('.mobile-navigation').count(), 0);
  assert.equal(await page.locator('.desktop-navigation').count(), 0);
  assert.equal(await page.locator('footer').count(), 0);
  await page.locator('.customer-auth-page:visible').getByLabel('Email', { exact: true }).fill('buyer@example.test');
  await page.locator('.customer-auth-page:visible').getByLabel('Password', { exact: true }).fill('test-password');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  assert.equal(await page.locator('.customer-auth-page:visible').getByLabel('Password', { exact: true }).getAttribute('type'), 'text');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await page.getByRole('link', { name: 'Sign up', exact: true }).click();
  await page.getByRole('heading', { name: 'Create customer account' }).waitFor();
  assert.equal(await page.locator('.customer-auth-page:visible').getByLabel('Confirm password', { exact: true }).count(), 1);
  await page.locator('.customer-auth-page:visible').getByLabel('Name', { exact: true }).fill('Signup draft');
  await mkdir('test-artifacts/customer-auth', { recursive: true });
  await page.screenshot({ path: 'test-artifacts/customer-auth/signup-mobile.png' });
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor();
  assert.equal(await page.locator('.customer-auth-page:visible').getByLabel('Email', { exact: true }).inputValue(), 'buyer@example.test');
  await page.goForward();
  await page.getByRole('heading', { name: 'Create customer account' }).waitFor();
  assert.equal(await page.locator('.customer-auth-page:visible').getByLabel('Name', { exact: true }).inputValue(), 'Signup draft');
  await page.goBack();
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor();
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert.equal(loginAttempts, 1);
  assert.equal(await page.locator('.customer-auth-page:visible').getByLabel('Email', { exact: true }).inputValue(), 'buyer@example.test');
  await page.screenshot({ path: 'test-artifacts/customer-auth/login-mobile.png' });
  await page.getByRole('button', { name: 'Change language' }).click();
  await page.locator('.auth-language').click();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  assert.equal(await search.inputValue(), 'Retained product search');
  assert.equal(initialLoads(), loads, 'Back must resume marketplace without a new initial fetch');
  await page.goto('http://127.0.0.1:5177/#/account/login?next=%2Fchats');
  await page.getByRole('heading', { name: 'Welcome back' }).waitFor();
  await page.locator('.customer-auth-page:visible').getByLabel('Email', { exact: true }).fill('buyer@example.test');
  await page.locator('.customer-auth-page:visible').getByLabel('Password', { exact: true }).fill('test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL('**/#/chats');
  assert.equal(await page.locator('.mobile-navigation').count(), 1);
  const guest = await browser.newPage({ viewport: { width: 1366, height: 900 } });
  await guest.goto('http://127.0.0.1:5177/#/account/register');
  await guest.getByRole('heading', { name: 'Create customer account' }).waitFor();
  await guest.getByRole('button', { name: 'Back', exact: true }).click();
  await guest.waitForURL('**/#/marketplace');
  await guest.close();
  console.log('PASS: standalone login/signup, page Back, browser Back/Forward, retained drafts/source search, sign-in failure/retry, language toggle, success destination and direct-link fallback. All authentication requests intercepted.');
} finally { await browser.close(); }
