export function translate(language, message, values = {}) {
  const template = language === "my" ? messages.get(message) || message : message;
  return template.replaceAll("_", " ").replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

export function useText() {
  const language = useContext(LocaleContext);
  return (message, values) => translate(language, message, values);
}

export function localizeError(language, message) {
  if (language !== "my" || !message) return message;
  if (/[\u1000-\u109f]/.test(message)) return message;
  if (messages.has(message)) return translate(language, message);
  const stock = message.match(/^Not enough available stock for (.+)\.$/);
  if (stock) return translate(language, "Not enough available stock for {name}.", { name: stock[1] });
  if (/proof.*(image|file|kilobytes|type|format|upload|max|2048)/i.test(message)) return translate(language, "Upload a JPG, PNG or WebP image no larger than 2 MB.");
  if (/email/i.test(message)) return translate(language, "Enter a valid email address.");
  if (/required/i.test(message)) return translate(language, "Please fill in all required fields.");
  if (/quantity|items\.\d+/i.test(message)) return translate(language, "Check the quantity and try again.");
  if (/too many/i.test(message)) return translate(language, "Too many requests. Please try again shortly.");
  if (/fetch|network|connection/i.test(message)) return translate(language, "Unable to connect. Please try again.");
  return translate(language, "Please check your details and try again. If the problem continues, contact the shop.");
}
